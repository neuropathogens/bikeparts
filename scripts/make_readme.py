"""Generate each part's README.md from its PartSpec, check results and slicer output.

Called by `uv run build`. The README is generated — never hand-edit it; change the part's
source (part.py / params.py) and rebuild.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from bikeparts.core.materials import MATERIALS, MaterialName
from bikeparts.parts import GATE3_TESTS, PartSpec
from checks import CheckResult, Status
from scripts.common import PARTS_SRC, Target
from scripts.slice import SliceResult

_REPO_URL = "https://github.com/neuropathogens/bikeparts"
_STATUS = {Status.PASS: "✅ pass", Status.FAIL: "❌ FAIL", Status.WAIVED: "⚠️ waived"}


@dataclass
class BodyResult:
    target: Target
    sliced: SliceResult | None
    checks: list[CheckResult]


def _bbox(t: Target) -> str:
    s = t.shape.bounding_box().size
    return f"{s.X:.1f} × {s.Y:.1f} × {s.Z:.1f}"


def _slice_cell(r: BodyResult) -> tuple[str, str]:
    if r.sliced is None:
        return "—", "—"
    return f"{r.sliced.grams * r.target.qty:.0f} g", r.sliced.time + (
        f" (× {r.target.qty})" if r.target.qty > 1 else ""
    )


def _fea_records(spec: PartSpec) -> list[dict[str, object]] | None:
    path = PARTS_SRC / spec.slug / "fea" / "results.json"
    if spec.load_cases is None or not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _gate2_status(spec: PartSpec) -> str:
    if spec.load_cases is None:
        return spec.fea
    recs = _fea_records(spec)
    if not recs:
        return "required — run `uv run fea`"
    if all(r["passes"] for r in recs):
        return (
            "✅ all load cases SF ≥ 3 ([results](#gate-2-fea)) — a screen with typical, "
            "unverified PETG values"
        )
    return "❌ failing ([results](#gate-2-fea))"


def _gate2_section(spec: PartSpec) -> list[str]:
    recs = _fea_records(spec)
    if not recs:
        return []
    out = [
        "### Gate 2: FEA",
        "",
        f"Linear static, quadratic tetrahedra (gmsh + scikit-fem), preset `{recs[0]['preset']}`. "
        "Safety factor = design strength (PETG tensile × 0.5 interlayer knockdown, "
        f"{recs[0]['design_strength_mpa']} MPa) ÷ the larger of the governing von Mises stress "
        "(away from where loads and supports are applied) and the bearing pressure. Raw peaks "
        "at load/support edges and contact-edge pressures are artifacts of idealised boundary "
        "conditions — they're listed so Gate 3 knows where to look. Rerun with `uv run fea`.",
        "",
        "| Case | Governing von Mises | Bearing | SF | Mesh change | Raw peak | Contact edge peak |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in recs:
        mark = "✅" if r["passes"] else "❌"
        change = "—" if r["mesh_change_pct"] is None else f"{r['mesh_change_pct']:+.0f} %"
        peak = r.get("contact_peak_mpa") or 0
        out.append(
            f"| `{r['case']}` | {r['max_von_mises_mpa']} MPa | {r['bearing_mpa']} MPa | "
            f"{mark} {r['safety_factor']} | {change} | {r['raw_max_von_mises_mpa']} MPa | "
            f"{peak if peak else '—'}{' MPa' if peak else ''} |"
        )
    out.append("")
    for r in recs:
        out += [f"**`{r['case']}`** — {r['description']}. Load source: {r['source']}.", ""]
        out += [f"![{r['case']}](fea/{r['case']}.png)", ""]
    return out


def render(spec: PartSpec, results: dict[str, list[BodyResult]]) -> str:
    default = spec.default_preset
    p0 = spec.presets[default]
    doc0 = spec.describe(p0)
    rows0 = results[default]
    gate1_ok = all(c.ok for rs in results.values() for r in rs for c in r.checks)
    any_sliced = any(r.sliced for rs in results.values() for r in rs)
    mat = MATERIALS[spec.material]

    out: list[str] = [
        "<!-- GENERATED by `uv run build` from part.py / params.py — do not edit by hand. -->",
        f"# {spec.title}",
        "",
        f"**{spec.tagline}**",
        "",
        f"Part {spec.number} of the [bikeparts]({_REPO_URL}) library · recommended material "
        f"**{spec.material}** · {len(spec.presets)} size presets from one source file",
        "",
        "> **Accessory only — no warranty.** This part is never in the rider's primary load "
        "path; its worst-case failure is losing the accessory, not control of the bike. It has "
        f"only been designed for {spec.material} printed in the orientation the files come in; "
        "**other materials and orientations are untested.** See [status](#validation-status).",
        "",
        "## Why",
        "",
        f"**Problem.** {spec.problem}",
        "",
        f"**What this does differently.** {spec.innovation}",
        "",
        f"## Drawings ({default})",
        "",
    ]
    for r in rows0:
        out += [f"**{r.target.body}**", "", f"![{r.target.body}](drawings/{r.target.body}.svg)", ""]

    out += [
        "## Print it",
        "",
        "| Setting | Value |",
        "|---|---|",
        f"| Material | {spec.material} (Tg ≈ {mat.glass_transition_c:g} °C, above the 70 °C heat floor) |"
        if mat.glass_transition_c
        else f"| Material | {spec.material} |",
        "| Orientation | as exported — do not rotate |",
        "| Supports | **off** (every part is designed to print without them) |",
        "| Layer height | 0.20 mm |",
        "| Perimeters | 3 (= the 1.2 mm minimum wall) |",
        "| Infill | 30 % gyroid |",
        "| Nozzle / bed | 0.4 mm, fits 220 × 220 mm |",
        "| Profiles | [`profiles/`](../../../../profiles) (PrusaSlicer, generic 220 mm printer) |",
        "",
        f"**Why this orientation.** {spec.orientation}",
        "",
    ]
    notes = [r.target for r in rows0 if r.target.note]
    for t in notes:
        out.append(f"- `{t.body}`: {t.note}")
    if notes:
        out.append("")

    out += [
        f"### Printed parts ({default})",
        "",
        "| Body | Qty | Material | Size (mm) | Filament | Print time |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows0:
        g, tm = _slice_cell(r)
        opt = " (optional)" if r.target.optional else ""
        out.append(
            f"| `{r.target.body}`{opt} | {r.target.qty} | {r.target.material} | {_bbox(r.target)} | {g} | {tm} |"
        )
    out.append("")
    if any_sliced:
        out += [
            "Grams and time from the PrusaSlicer CLI with the profiles above on a generic, "
            "conservatively-tuned 220 mm printer; fast printers will be quicker.",
            "",
        ]
    else:
        out += [
            "_PrusaSlicer was not available when this README was built: no grams or times._",
            "",
        ]

    out += ["### Files", ""]
    out += [
        "STEP (editable in Fusion/FreeCAD/Onshape), STL and 3MF for every preset are built by "
        "CI on every commit (download the `out` artifact from the latest run under **Actions**) "
        "or locally:",
        "",
        "```sh",
        f"uv run build --part {spec.slug}     # → out/{spec.slug}/<preset>/<body>.step|stl|3mf|svg",
        "```",
        "",
        "## Hardware",
        "",
    ]
    out += [f"- {h}" for h in doc0.hardware]
    out += ["", "## Assembly", ""]
    out += [f"{i}. {step}" for i, step in enumerate(doc0.assembly, 1)]
    out += ["", "## Presets", ""]

    for preset, rows in results.items():
        doc = spec.describe(spec.presets[preset])
        total_g = sum(
            r.sliced.grams * r.target.qty for r in rows if r.sliced and not r.target.optional
        )
        summary = f"<b>{preset}</b>" + (f" — {total_g:.0f} g" if any_sliced else "")
        out += [f"<details{' open' if preset == default else ''}><summary>{summary}</summary>", ""]
        out += ["| | |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in doc.facts.items()]
        out += ["", "| Body | Qty | Size (mm) | Filament | Time |", "|---|---|---|---|---|"]
        for r in rows:
            g, tm = _slice_cell(r)
            out.append(f"| `{r.target.body}` | {r.target.qty} | {_bbox(r.target)} | {g} | {tm} |")
        if doc.hardware != doc0.hardware:
            out += ["", "Hardware: " + "; ".join(doc.hardware)]
        out += ["", "</details>", ""]

    out += [
        "## Validation status",
        "",
        "| Gate | Status |",
        "|---|---|",
        f"| 1 — automated geometry checks | {'✅ all presets pass' if gate1_ok else '❌ failing'} "
        "(table below) |",
        f"| 2 — FEA | {_gate2_status(spec)} |",
        "| 3 — physical test | **Not yet tested.** Results will go in "
        f"[`test-reports/{spec.slug}/`](../../../../test-reports). |",
        "",
        "### Gate 1 results",
        "",
        "| Preset / body | " + " | ".join(c.check for c in rows0[0].checks) + " |",
        "|---|" + "---|" * len(rows0[0].checks),
    ]
    for preset, rows in results.items():
        for r in rows:
            cells = [_STATUS[c.status] for c in r.checks]
            out.append(f"| {preset} / `{r.target.body}` | " + " | ".join(cells) + " |")
    out.append("")

    out += _gate2_section(spec)

    exempt = sorted({e.reason for rs in results.values() for r in rs for e in r.target.exempt})
    if exempt or spec.exceptions:
        out += ["### Rule exceptions", ""]
        out += [f"- Label region excluded from overhang/min_wall: {e}" for e in exempt]
        out += [f"- `{k}` waived: {v}" for k, v in spec.exceptions.items()]
        out.append("")

    if spec.gate3:
        out += [
            "### Gate 3 tests to run",
            "",
            "Print in the recommended material with the `profiles/`. Paint-mark every bolt head first.",
            "",
            "| Test | Method | Pass criterion | Result |",
            "|---|---|---|---|",
        ]
        for key in spec.gate3:
            name, method, crit = GATE3_TESTS[key]
            out.append(f"| {name} | {method} | {crit} | pending |")
        out.append("")

    if spec.extra_readme:
        out += [spec.extra_readme.rstrip(), ""]

    if spec.assumptions:
        out += ["## Assumptions to verify", ""]
        out += [f"- {a}" for a in spec.assumptions]
        out.append("")
    unverified = MATERIALS[MaterialName.PETG].verified is False
    if unverified:
        out += [
            "Material strengths in `core/materials.py` are typical values, not your filament's "
            "datasheet, until someone enters and verifies them.",
            "",
        ]

    out += [
        "## License",
        "",
        "Design files CERN-OHL-S-2.0 · code Apache-2.0 · this README and drawings CC BY-SA 4.0. "
        "See [LICENSE.md](../../../../LICENSE.md). Compatibility names (e.g. AirTag) describe "
        "fit only; this project isn't affiliated with any brand.",
        "",
    ]
    return "\n".join(out)


def write(spec: PartSpec, results: dict[str, list[BodyResult]], drawings: dict[str, Path]) -> Path:
    part_dir = PARTS_SRC / spec.slug
    ddir = part_dir / "drawings"
    ddir.mkdir(exist_ok=True)
    for old in ddir.glob("*.svg"):
        old.unlink()
    for body, svg in drawings.items():
        (ddir / f"{body}.svg").write_text(svg.read_text(encoding="utf-8"), encoding="utf-8")
    readme = part_dir / "README.md"
    readme.write_text(render(spec, results), encoding="utf-8")
    return readme
